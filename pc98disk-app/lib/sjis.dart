bool _isLead(int b) => (b >= 0x81 && b <= 0x9F) || (b >= 0xE0 && b <= 0xFC);

/// Shift_JIS(cp932) のバイト列を文字列にする。変換できない所は '?'。
/// 0x1A (EOF) 以降は stopAtEof=true で切り捨てる。
String sjisDecode(List<int> bytes, {bool stopAtEof = false, bool keepControl = true}) {
  final out = <int>[];
  var i = 0;
  final n = bytes.length;
  while (i < n) {
    final b = bytes[i];
    if (b == 0x1A && stopAtEof) break;
    if (b < 0x80) {
      if (b >= 0x20 || b == 0x0A || b == 0x0D || b == 0x09 || keepControl && b == 0x1B) {
        out.add(b);
      } else if (!keepControl) {
        out.add(0x3F);
      }
      i++;
    } else if (b >= 0xA1 && b <= 0xDF) {
      out.add(0xFF61 + b - 0xA1);
      i++;
    } else if (_isLead(b) && i + 1 < n) {
      final t = bytes[i + 1];
      if (t >= 0x40 && t <= 0xFC && t != 0x7F) {
        final li = b <= 0x9F ? b - 0x81 : b - 0xC1;
        final v = _tbl.getUint16((li * 189 + (t - 0x40)) * 2, Endian.little);
        out.add(v == 0xFFFD ? 0x3F : v);
        i += 2;
      } else {
        out.add(0x3F);
        i++;
      }
    } else {
      out.add(0x3F);
      i++;
    }
  }
  return String.fromCharCodes(out);
}

Map<int, int>? _rev;

/// 文字列を Shift_JIS(cp932) のバイト列にする。変換できない文字があれば null。
Uint8List? sjisEncode(String s) {
  var rev = _rev;
  if (rev == null) {
    rev = <int, int>{};
    for (var li = 0; li < 60; li++) {
      final lead = li <= 0x1E ? li + 0x81 : li + 0xC1;
      for (var t = 0; t < 189; t++) {
        final v = _tbl.getUint16((li * 189 + t) * 2, Endian.little);
        if (v != 0xFFFD) rev.putIfAbsent(v, () => (lead << 8) | (t + 0x40));
      }
    }
    _rev = rev;
  }
  final out = BytesBuilder();
  for (final u in s.runes) {
    if (u < 0x80) {
      out.addByte(u);
    } else if (u >= 0xFF61 && u <= 0xFF9F) {
      out.addByte(0xA1 + u - 0xFF61);
    } else {
      final d = rev[u];
      if (d == null) return null;
      out.addByte(d >> 8);
      out.addByte(d & 0xFF);
    }
  }
  return out.takeBytes();
}
